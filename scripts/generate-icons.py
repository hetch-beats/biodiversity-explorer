#!/usr/bin/env python3
"""
Regenerates src/renderer/components/icons.tsx from Lucide's SVG sources, so
icon shapes are copied verbatim rather than hand-drawn. Usage:

  git clone --depth 1 --filter=blob:none --sparse https://github.com/lucide-icons/lucide /tmp/lucide
  (cd /tmp/lucide && git sparse-checkout set icons)
  python3 scripts/generate-icons.py /tmp/lucide

To add an icon, add it to ICONS below (component suffix -> Lucide file name).
"""
import re, subprocess, sys, pathlib

ICONS = {
    'X': 'x', 'Check': 'check', 'Settings': 'settings',
    'PanelLeftClose': 'panel-left-close', 'PanelLeftOpen': 'panel-left-open',
    'RefreshCw': 'refresh-cw', 'Star': 'star', 'Maximize2': 'maximize-2', 'Search': 'search',
    'SlidersHorizontal': 'sliders-horizontal', 'ExternalLink': 'external-link', 'ImageOff': 'image-off',
    'LoaderCircle': 'loader-circle', 'ChevronLeft': 'chevron-left', 'ChevronRight': 'chevron-right',
    'CircleAlert': 'circle-alert', 'Eye': 'eye', 'EyeOff': 'eye-off', 'List': 'list',
}

lucide = pathlib.Path(sys.argv[1])
out_path = pathlib.Path(__file__).resolve().parent.parent / 'src/renderer/components/icons.tsx'
rev = subprocess.run(['git', '-C', str(lucide), 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
license_text = (lucide / 'LICENSE').read_text().strip()

def to_jsx(el):
    return re.sub(r'\s([a-z]+)-([a-z][a-z-]*)=',
                  lambda m: ' ' + m.group(1) + re.sub(r'(^|-)([a-z])', lambda n: n.group(2).upper(), m.group(2)) + '=', el)

license_block = '\n'.join((' *   ' + l).rstrip() for l in license_text.splitlines())
parts = [f"""/*
 * GENERATED by scripts/generate-icons.py — do not edit by hand.
 *
 * Icons from Lucide (https://lucide.dev), generated from the SVG sources in
 * github.com/lucide-icons/lucide@{rev[:12]} (icons/*.svg) — shape data copied
 * verbatim, not redrawn. Bundled locally: no dependency, works offline.
 *
 * Lucide is licensed under the ISC License (verbatim copy of its LICENSE):
 *
{license_block}
 */
import type {{ ReactNode, SVGProps }} from 'react'

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'children'> {{
  size?: number
  /** Fill the shape with currentColor (e.g. a filled star). */
  filled?: boolean
}}

function Icon({{ size = 16, filled = false, strokeWidth = 2, children, ...rest }}: IconProps & {{ children: ReactNode }}): JSX.Element {{
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={{size}}
      height={{size}}
      viewBox="0 0 24 24"
      fill={{filled ? 'currentColor' : 'none'}}
      stroke="currentColor"
      strokeWidth={{strokeWidth}}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {{...rest}}
    >
      {{children}}
    </svg>
  )
}}
"""]
for comp, name in ICONS.items():
    svg = (lucide / 'icons' / f'{name}.svg').read_text()
    inner = re.search(r'<svg[^>]*>(.*)</svg>', svg, re.S).group(1)
    els = [to_jsx(e.strip()) for e in re.findall(r'<(?:path|circle|rect|line|polyline|polygon|ellipse)\b[^>]*/>', inner)]
    if not els:
        sys.exit(f'no shapes parsed for {name}')
    body = '\n'.join('      ' + e for e in els)
    parts.append(f"""
export function Icon{comp}(props: IconProps): JSX.Element {{
  return (
    <Icon {{...props}}>
{body}
    </Icon>
  )
}}""")
out_path.write_text('\n'.join(parts) + '\n')
print(f'wrote {len(ICONS)} icons to {out_path} (lucide {rev[:12]})')
